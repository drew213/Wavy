"""Schema migrations with Alembic. Every change to the database's shape is a revision in migrations/versions/.

upgrade() is what `wavyos init-db` runs on every deploy. A database made before migrations existed
(by create_all) has tables but no alembic_version: it gets any missing tables, is stamped at the
baseline, and then upgraded like any other.

To change a model: edit models.py, run `wavyos db-revision -m "what changed"`, read the generated file,
and commit both. Tests fail if the models and the migrations disagree.
"""
from __future__ import annotations

import re
import tempfile
from contextlib import nullcontext
from pathlib import Path
from typing import Optional

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.operations import Operations
from alembic.script import ScriptDirectory
from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine

from .db import Base, make_engine

SCRIPTS = Path(__file__).parent / "migrations"
BASELINE = "0001"
MIGRATION_LOCK = 0x57A7_0001


def config(connection=None) -> Config:
    cfg = Config()
    cfg.set_main_option("script_location", str(SCRIPTS))
    if connection is not None:
        cfg.attributes["connection"] = connection
    return cfg


def current(engine: Engine) -> Optional[str]:
    with engine.connect() as conn:
        return MigrationContext.configure(conn).get_current_revision()


def head() -> str:
    return ScriptDirectory.from_config(config()).get_current_head()


def upgrade(engine: Engine) -> str:
    """Bring the database to the latest revision. Returns what was done, for the deploy log."""
    from . import models  # noqa: F401  (registers every table)
    with engine.begin() as conn:
        if conn.dialect.name == "postgresql":  # the web pre-deploy and the worker both run init-db
            conn.execute(text("SELECT pg_advisory_xact_lock(:k)"), {"k": MIGRATION_LOCK})
        insp = inspect(conn)
        legacy = not insp.has_table("alembic_version") and insp.has_table("organizations")
        if legacy:  # fill in any baseline tables it lacks; later revisions add the rest
            _create_missing_baseline(conn)
            command.stamp(config(conn), BASELINE)
        before = MigrationContext.configure(conn).get_current_revision()
        command.upgrade(config(conn), "head")
        after = MigrationContext.configure(conn).get_current_revision()
    if legacy:
        return f"existing database adopted at {BASELINE}, now at {after}"
    return f"database at {after}" if before == after else f"database upgraded {before or 'empty'} -> {after}"


def _create_missing_baseline(conn) -> None:
    """Create the tables the baseline has and the database lacks, exactly as the baseline made them.
    Today's models would make them in their latest shape, which the revisions after the baseline can't apply to."""
    existing = set(inspect(conn).get_table_names())
    baseline = ScriptDirectory.from_config(config()).get_revision(BASELINE).module
    real_op = baseline.op
    baseline.op = _MissingTablesOnly(Operations(MigrationContext.configure(conn)), existing)
    try:
        baseline.upgrade()
    finally:
        baseline.op = real_op


class _MissingTablesOnly:
    """Stands in for alembic's op while the baseline runs: skips every table that already exists."""

    def __init__(self, ops: Operations, existing: set[str]):
        self._ops, self._existing = ops, existing

    def create_table(self, name, *columns, **kw):
        if name not in self._existing:
            return self._ops.create_table(name, *columns, **kw)

    def batch_alter_table(self, name, **kw):
        return nullcontext(_Skipped()) if name in self._existing else self._ops.batch_alter_table(name, **kw)

    def __getattr__(self, attr):
        return getattr(self._ops, attr)


class _Skipped:
    @staticmethod
    def f(name):
        return name

    def __getattr__(self, attr):
        return lambda *args, **kw: None


def differences(engine: Engine) -> list:
    """What the models have that the database doesn't (or vice versa). Empty when they agree."""
    from . import models  # noqa: F401
    with engine.connect() as conn:
        ctx = MigrationContext.configure(conn, opts={"compare_type": True})
        return compare_metadata(ctx, Base.metadata)


def new_revision(message: str) -> Path:
    """Write the next revision, autogenerated from the models against a scratch database at head."""
    versions = SCRIPTS / "versions"
    numbers = [int(m.group(1)) for p in versions.glob("*.py") if (m := re.match(r"(\d{4})_", p.name))]
    rev = f"{max(numbers, default=0) + 1:04d}"
    with tempfile.TemporaryDirectory() as tmp:
        engine = make_engine(f"sqlite:///{tmp}/scratch.db")
        upgrade(engine)
        with engine.begin() as conn:
            command.revision(config(conn), message=message, autogenerate=True, rev_id=rev)
        engine.dispose()
    return next(versions.glob(f"{rev}_*.py"))
